#!/usr/bin/env node
/* Regenerate every DERIVED sector/type view from the master — Charter 4B.
 *
 * Source (only): data/reference/instruments.json. Outputs (all marked
 * derived; never edit by hand, never treat as a source of truth):
 *  1. js/nd-master.js — window.ND_MASTER compact map for browser pages
 *     that cannot fetch the master synchronously (sectors, screener,
 *     daily). Pages include it (defer, in order) before their own script.
 *  2. data/reference/instruments-view.json — compact fetchable view
 *     {symbol: {type, sector|null}} for async consumers and for the
 *     live gate until 4C points it at the master directly.
 *  3. tools/sector-map.json — DERIVED VIEW ONLY (see
 *     tools/sector-map.DERIVED.md). The old classifier-built file is
 *     gone as a source of truth; this file survives in 4B ONLY because
 *     the live gate currently reads a served sector map, and deleting
 *     it before 4C updates the gate would break the gate. 4C retires it.
 *     UNCONFIRMED rows carry sector: null (no sector asserted).
 *
 * Usage: node tools/build-master-view.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const M = require('./master-instruments.js');

const ROOT = path.join(__dirname, '..');
const { rows } = M.load();
const syms = Object.keys(rows).sort();
const NOTE = 'DERIVED from data/reference/instruments.json (Charter v4.2 item 4A master) — ' +
  'regenerated by tools/build-master-view.js. NOT a source of truth. ' +
  'sector null = UNCONFIRMED in the master (no sector asserted, never a bucket).';

// 1. js/nd-master.js
const compact = {};
for (const s of syms) compact[s] = [rows[s].type, rows[s].sector];
const js = '/* ' + NOTE + ' */\n' +
  '(function () {\n' +
  "  'use strict';\n" +
  '  var MAP = ' + JSON.stringify(compact) + ';\n' +
  '  var SECTORS = ' + JSON.stringify(M.MASTER_SECTORS) + ';\n' +
  '  function row(sym) { return MAP[String(sym || "").toUpperCase()] || null; }\n' +
  '  window.ND_MASTER = {\n' +
  '    version: 1, source: "data/reference/instruments.json", derived: true,\n' +
  '    sectors: SECTORS,\n' +
  '    sectorOf: function (sym) { var r = row(sym); return r ? r[1] : null; },\n' +
  '    typeOf: function (sym) { var r = row(sym); return r ? r[0] : null; },\n' +
  '    isEquity: function (sym) { var r = row(sym); return !!r && r[0] === "EQUITY"; },\n' +
  '    isMasterSector: function (s) { return SECTORS.indexOf(s) >= 0; }\n' +
  '  };\n' +
  '})();\n';
fs.writeFileSync(path.join(ROOT, 'js', 'nd-master.js'), js);

// 2. data/reference/instruments-view.json
const view = { derived_from: 'data/reference/instruments.json', derived_by: 'tools/build-master-view.js',
  note: NOTE, count: syms.length, rows: {} };
for (const s of syms) view.rows[s] = { type: rows[s].type, sector: rows[s].sector };
fs.writeFileSync(path.join(ROOT, 'data', 'reference', 'instruments-view.json'),
  JSON.stringify(view, null, 1) + '\n');

// 3. tools/sector-map.json (derived view; gate-safety keep, see DERIVED.md)
const smap = {};
for (const s of syms) {
  smap[s] = { sector: rows[s].sector, instrument_type: rows[s].type,
    derived_from: 'data/reference/instruments.json', derived: true };
}
fs.writeFileSync(path.join(__dirname, 'sector-map.json'), JSON.stringify(smap, null, 1) + '\n');

console.log('master view: ' + syms.length + ' rows -> js/nd-master.js, ' +
  'data/reference/instruments-view.json, tools/sector-map.json (derived)');
