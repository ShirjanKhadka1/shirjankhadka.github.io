#!/usr/bin/env node
/* ============================================================
   build-company-logos.js
   Regenerates js/company-logos.js from data/company-logos.json.
   Usage: node tools/build-company-logos.js
   The manifest maps SYMBOL -> '/assets/logos/<file>'; the logo
   files themselves are sourced from official company websites,
   normalized to webp (max 192px), and committed under assets/logos/.
   ============================================================ */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'data', 'company-logos.json');
const OUT = path.join(ROOT, 'js', 'company-logos.js');

const manifest = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const logos = manifest.logos || {};

// Validate: every mapped file must exist under the repo (catch typos).
const missing = [];
Object.entries(logos).forEach(([sym, p]) => {
  const rel = String(p).replace(/^\//, '');
  if (!fs.existsSync(path.join(ROOT, rel))) missing.push(sym + ' -> ' + p);
});
if (missing.length) {
  console.error('Missing logo files:\n  ' + missing.join('\n  '));
  process.exit(1);
}

const out =
  '/* GENERATED by tools/build-company-logos.js — do not edit by hand.\n' +
  '   Source of truth: data/company-logos.json (official company websites only). */\n' +
  'window.NEPSE_LOGOS = ' + JSON.stringify(logos) + ';\n';
fs.writeFileSync(OUT, out);
console.log('wrote ' + OUT + ' with ' + Object.keys(logos).length + ' logos');
